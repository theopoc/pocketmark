#!/usr/bin/env bash
# Per-worktree development environment.
#
# Gives the current checkout/worktree its own block of 10 host ports and its
# own Compose project name, records both in the git-ignored .env.worktree and
# wraps `docker compose` so every call uses them. Safe to re-run: an existing
# allocation is reused and the env file is only rewritten when its content
# changes.
#
#   scripts/dev_env.sh init      allocate + write .env.worktree (default)
#   scripts/dev_env.sh print     print KEY=value pairs (project, port, range, url)
#   scripts/dev_env.sh project   print the Compose project name only
#   scripts/dev_env.sh compose … run `docker compose` for this worktree's stack
#   scripts/dev_env.sh release   free this worktree's slot (used by dev_clean.sh, make down)
#
# Tunables (environment): POCKETMARK_DEV_PORT_BASE (8000), POCKETMARK_DEV_SLOTS (8).
# Slot N owns BASE+10N .. BASE+10N+9; the app is published on the first port,
# the other nine are reserved for this worktree (debugger, Vite, extra services).
set -euo pipefail

BASE=${POCKETMARK_DEV_PORT_BASE:-8000}
SLOTS=${POCKETMARK_DEV_SLOTS:-8}
SPAN=10
ENV_FILE=.env.worktree

die() { echo "dev_env: $*" >&2; exit 1; }

root=$(git rev-parse --show-toplevel 2>/dev/null) || die "not inside a git checkout"
common=$(git rev-parse --path-format=absolute --git-common-dir)
registry="$common/pocketmark-dev-slots"
lock="$registry.lock"

project_name() {
  local name hash
  name=$(basename "$root" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9\n' '-' | tr -s '-' | sed 's/^-*//;s/-*$//' | cut -c1-30)
  hash=$(printf '%s' "$root" | cksum | cut -d' ' -f1)
  printf 'pocketmark-%s-%s' "${name:-wt}" "$((hash % 100000))"
}

acquire_lock() {
  local tries=0
  until mkdir "$lock" 2>/dev/null; do
    tries=$((tries + 1))
    [ "$tries" -le 100 ] || die "registry locked ($lock); remove it if no other dev_env.sh is running"
    sleep 0.1
  done
  trap 'rmdir "$lock" 2>/dev/null || true' EXIT
}

slot_of_root() {
  [ -f "$registry" ] || return 0
  awk -F'\t' -v p="$root" '$2 == p { print $1; exit }' "$registry"
}

# Drop registry entries whose worktree directory no longer exists.
prune_registry() {
  [ -f "$registry" ] || return 0
  local tmp="$registry.tmp.$$" s p
  while IFS=$'\t' read -r s p; do
    if [ -d "$p" ]; then printf '%s\t%s\n' "$s" "$p"; fi
  done <"$registry" >"$tmp"
  mv "$tmp" "$registry"
}

port_busy() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

allocate_slot() {
  local slot used s p base busy
  acquire_lock
  prune_registry
  slot=$(slot_of_root)
  if [ -z "$slot" ]; then
    used=$(cut -f1 "$registry" 2>/dev/null || true)
    for ((s = 0; s < SLOTS; s++)); do
      if grep -qx "$s" <<<"$used"; then continue; fi
      base=$((BASE + s * SPAN))
      busy=0
      for ((p = base; p < base + SPAN; p++)); do
        if port_busy "$p"; then busy=1; break; fi
      done
      if [ "$busy" = 0 ]; then
        slot=$s
        printf '%s\t%s\n' "$slot" "$root" >>"$registry"
        break
      fi
    done
    [ -n "$slot" ] || die "no free slot (all $SLOTS slots taken or in use); free one with scripts/dev_clean.sh"
  fi
  printf '%s' "$slot"
}

render_env() { # $1 = slot
  local project base
  project=$(project_name)
  base=$((BASE + $1 * SPAN))
  cat <<EOF
# Generated by scripts/dev_env.sh. Do not edit; ignored by git.
COMPOSE_PROJECT_NAME=$project
POCKETMARK_DEV_SLOT=$1
POCKETMARK_DEV_PORT=$base
POCKETMARK_DEV_PORT_RANGE=$base-$((base + SPAN - 1))
POCKETMARK_DEV_IMAGE=$project:dev
POCKETMARK_DEV_URL=http://127.0.0.1:$base
EOF
}

cmd_init() {
  local slot
  slot=$(allocate_slot)
  render_env "$slot" >"$root/$ENV_FILE.tmp"
  if cmp -s "$root/$ENV_FILE.tmp" "$root/$ENV_FILE"; then
    rm -f "$root/$ENV_FILE.tmp"
  else
    mv "$root/$ENV_FILE.tmp" "$root/$ENV_FILE"
  fi
  [ "${QUIET:-0}" = 1 ] || cmd_print
}

cmd_print() {
  [ -f "$root/$ENV_FILE" ] || die "$ENV_FILE missing; run make up"
  grep -v '^#' "$root/$ENV_FILE"
}

cmd_compose() {
  QUIET=1 cmd_init
  cd "$root"
  exec docker compose -p "$(project_name)" --env-file "$ENV_FILE" -f compose.dev.yaml "$@"
}

cmd_release() {
  [ -f "$registry" ] || return 0
  acquire_lock
  local tmp="$registry.tmp.$$" s p
  while IFS=$'\t' read -r s p; do
    if [ "$p" != "$root" ]; then printf '%s\t%s\n' "$s" "$p"; fi
  done <"$registry" >"$tmp"
  mv "$tmp" "$registry"
}

case "${1:-init}" in
  init) cmd_init ;;
  print) cmd_print ;;
  project) project_name; echo ;;
  compose) shift; cmd_compose "$@" ;;
  release) cmd_release ;;
  *) die "unknown command '$1' (init|print|project|compose|release)" ;;
esac
