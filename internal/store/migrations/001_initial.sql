CREATE FUNCTION advance_dav_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        DELETE FROM dav_ids WHERE kind=TG_ARGV[0] AND local_id=OLD.id;
    END IF;
    UPDATE dav_revision SET value=value+1, modified=epoch_seconds() WHERE id=1;
    RETURN NULL;
END $$;
CREATE TRIGGER dav_link_change AFTER INSERT OR DELETE ON links FOR EACH ROW EXECUTE FUNCTION advance_dav_revision('bookmark');
CREATE TRIGGER dav_link_update AFTER UPDATE OF url,title,description,collection_id ON links FOR EACH ROW
WHEN ((NEW.url,NEW.title,NEW.description,NEW.collection_id) IS DISTINCT FROM (OLD.url,OLD.title,OLD.description,OLD.collection_id))
EXECUTE FUNCTION advance_dav_revision('bookmark');
CREATE TRIGGER dav_collection_change AFTER INSERT OR DELETE ON collections FOR EACH ROW EXECUTE FUNCTION advance_dav_revision('folder');
CREATE TRIGGER dav_collection_update AFTER UPDATE OF name,parent_id ON collections FOR EACH ROW
WHEN ((NEW.name,NEW.parent_id) IS DISTINCT FROM (OLD.name,OLD.parent_id)) EXECUTE FUNCTION advance_dav_revision('folder');

CREATE FUNCTION near_metadata(terms text[], metadata text) RETURNS boolean
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT cardinality(terms) BETWEEN 1 AND 16 AND NOT EXISTS (
        SELECT FROM unnest(terms) t(term) WHERE NOT EXISTS (
            SELECT FROM regexp_split_to_table(lower(metadata COLLATE pg_unicode_fast), '[^[:alnum:]]+') w(word)
            WHERE starts_with(word,lower(term COLLATE pg_unicode_fast)) OR
            CASE WHEN length(term) BETWEEN 4 AND 80 AND length(word) <= 80
                THEN levenshtein_less_equal(lower(term COLLATE pg_unicode_fast),word,1) <= 1 ELSE false END
        )
    )
$$;

-- Preserve case, accents and punctuation in the displayed excerpt while
-- matching the same Unicode word prefixes as the stored search vector.
CREATE FUNCTION search_excerpt(fields text[], terms text[]) RETURNS text
LANGUAGE plpgsql STABLE AS $$
DECLARE
    field text;
    part text;
    prefix text;
    snippet text;
    normalized text[];
BEGIN
    SELECT array_agg(lower(unaccent(t) COLLATE pg_unicode_fast)) INTO normalized FROM unnest(terms) t;
    FOREACH field IN ARRAY fields LOOP
        prefix := '';
        snippet := NULL;
        FOR part IN SELECT m[1] FROM regexp_matches(field COLLATE pg_unicode_fast, '[[:alnum:]]+|[^[:alnum:]]+', 'g') m LOOP
            IF EXISTS (SELECT FROM unnest(normalized) t WHERE starts_with(lower(unaccent(part) COLLATE pg_unicode_fast),t)) THEN
                snippet := coalesce(snippet,prefix) || chr(30) || left(part,200) || chr(31);
            ELSIF snippet IS NULL THEN
                prefix := right(prefix || right(part,80),80);
            ELSE
                snippet := snippet || left(part,300);
            END IF;
            IF length(snippet) >= 300 THEN RETURN left(snippet,600); END IF;
        END LOOP;
        IF snippet IS NOT NULL THEN RETURN snippet; END IF;
    END LOOP;
    RETURN '';
END $$;
