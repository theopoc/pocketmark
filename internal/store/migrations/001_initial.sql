CREATE FUNCTION epoch_seconds() RETURNS bigint
LANGUAGE sql STABLE AS $$ SELECT floor(extract(epoch FROM now()))::bigint $$;

CREATE FUNCTION utc_timestamp_text() RETURNS text
LANGUAGE sql STABLE AS $$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"') $$;

