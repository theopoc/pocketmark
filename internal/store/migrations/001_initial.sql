CREATE TEXT SEARCH CONFIGURATION pocketmark_search (COPY = pg_catalog.simple);
ALTER TEXT SEARCH CONFIGURATION pocketmark_search ALTER MAPPING FOR word, hword, hword_part
WITH unaccent, simple;
CREATE FUNCTION update_search_vector() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.search_vector := to_tsvector('pocketmark_search', regexp_replace(lower(unaccent(concat_ws(' ',NEW.title,NEW.url,NEW.description,NEW.notes,NEW.tags,NEW.content)) COLLATE pg_unicode_fast), '[^[:alnum:]]+', ' ', 'g'));
    RETURN NEW;
END $$;
CREATE TRIGGER update_link_search BEFORE INSERT OR UPDATE OF title,url,description,notes,tags,content ON links
FOR EACH ROW EXECUTE FUNCTION update_search_vector();
CREATE FUNCTION record_link_tags() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO compat_tags(name) SELECT DISTINCT value FROM jsonb_array_elements_text(NEW.tags::jsonb) ORDER BY value
    ON CONFLICT (name) DO NOTHING;
    RETURN NULL;
END $$;
CREATE TRIGGER record_link_tags AFTER INSERT OR UPDATE OF tags ON links FOR EACH ROW EXECUTE FUNCTION record_link_tags();
CREATE FUNCTION clear_thumbnail() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN DELETE FROM thumbnails WHERE link_id=NEW.id; RETURN NULL; END $$;
CREATE TRIGGER thumbnail_url_change AFTER UPDATE OF url ON links FOR EACH ROW WHEN (NEW.url <> OLD.url) EXECUTE FUNCTION clear_thumbnail();

