-- PostgreSQL btree entries cannot hold every supported 4096-byte URL.
CREATE FUNCTION url_digest(text) RETURNS bytea LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
AS $$ SELECT sha256(convert_to($1, 'UTF8')) $$;
CREATE UNIQUE INDEX links_url ON links (url_digest(url));
CREATE INDEX links_collection ON links(collection_id,id DESC);
-- Dates accepted by the application are RFC3339 and always carry a zone.
